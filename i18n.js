// 英語にしたときの、計算のエラーの文言（cube-core.js の日本語の文言に対応）
const ERR_EN = {
  '角のピースが不正です': 'Invalid corner piece',
  '角の向きが不正です': 'Invalid corner orientation',
  '角の並びが不正です': 'Invalid corner arrangement',
  '辺のピースが不正です': 'Invalid edge piece',
  '辺の向きが不正です': 'Invalid edge orientation',
  '辺の並びが不正です': 'Invalid edge arrangement',
  '同じピースが重なっています': 'Some pieces are duplicated',
  '組み合わせが不可能です（偶奇が合いません）': 'This combination is impossible (even/odd does not match)',
  '角の向きの合計が不正です': 'The corner orientations do not add up',
  '辺の向きの合計が不正です': 'The edge orientations do not add up',
  '範囲外の値です': 'Value out of range',
};

export function getLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'en' || q === 'ja') return q;
  try {
    const saved = localStorage.getItem('lang');
    if (saved === 'en' || saved === 'ja') return saved;
  } catch (e) {
    // 保存できないブラウザでは、日本語で表示する
  }
  return 'ja';
}

// 文言を取り出す（{名前} の部分を vars で置き換える）
export function t(key, vars = {}) {
  const s = DICT[getLang()][key] ?? DICT.ja[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

// 計算のエラーを、今の言語の文言にする
export function tErr(msg) {
  return getLang() === 'en' ? (ERR_EN[msg] ?? msg) : msg;
}

// 画面の文言を入れ替える（data-i18n は文言、data-i18n-title は title、data-i18n-alt は alt）
export function applyI18n() {
  document.documentElement.lang = getLang();
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => { el.alt = t(el.dataset.i18nAlt); });
}

// 言語を変える。保存してからページを読み直すので、どの画面も必ず同じ言語になる。
export function setLang(lang) {
  try {
    localStorage.setItem('lang', lang);
  } catch (e) {
    // 保存できないブラウザでは、読み直したあとは日本語になることがある
  }
  const url = new URL(location.href);
  url.searchParams.delete('lang');
  location.replace(url.toString());
}

// 右上の切り替え
function updateSwitch() {
  document.querySelectorAll('.langsw button').forEach((b) => {
    b.setAttribute('aria-pressed', String(b.dataset.lang === getLang()));
  });
}

export function mountLangSwitch() {
  const style = document.createElement('style');
  style.textContent = `
    .langsw { position: fixed; top: 8px; right: 8px; z-index: 10; display: flex; gap: 4px; }
    .langsw button { font-size: 0.85rem; padding: 4px 8px; border: 1px solid #888; border-radius: 4px; background: #fff; color: #222; cursor: pointer; }
    .langsw button[aria-pressed="true"] { background: #222; color: #fff; }`;
  document.head.appendChild(style);
  const box = document.createElement('div');
  box.className = 'langsw';
  for (const lang of ['ja', 'en']) {
    const b = document.createElement('button');
    b.dataset.lang = lang;
    b.textContent = lang === 'ja' ? '日本語' : 'English';
    b.addEventListener('click', () => setLang(lang));
    box.appendChild(b);
  }
  document.body.appendChild(box);
  updateSwitch();
}
